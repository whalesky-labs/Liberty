import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseRuntimeModelPins, runtimeModelPinsPath } from './lib/runtime-model-pins.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const runtime = 'packages/desktop-resources/runtime';
const inputs = new Map([
 ['runtime-manifest.json', `${runtime}/runtime-manifest.json`],
 ...['runner.py', 'runtime_validate.py', 'runtime_warmup.py', 'requirements-lock-darwin-aarch64.txt', 'requirements-lock-darwin-x64.txt', 'requirements-lock-windows-x64.txt'].map(name => [name, `python/funasr-runner/${name}`]),
 ['build_vendor_wheel.py', 'python/funasr-runner/tools/build_vendor_wheel.py'],
 ['funasr-1.3.9.json', 'python/funasr-runner/vendor/funasr-1.3.9.json'],
]);
const models = parseRuntimeModelPins(await readFile(path.join(root, runtimeModelPinsPath), 'utf8'));
const metadataScript = await readFile(path.join(root, runtime, 'publish_model_cache.py'), 'utf8');
if (!metadataScript.trim()) throw new Error('ModelScope publishing script missing');
const lines = ['// Code generated by scripts/generate-native-runtime.mjs; DO NOT EDIT.', '// Original runtime manifest, Python scripts, locks and pinned model registry.', 'package managed', '', 'var resources = map[string]string{'];
for (const [name, file] of inputs) lines.push(`${JSON.stringify(name)}: ${JSON.stringify(await readFile(path.join(root, file), 'utf8'))},`);
lines.push(`"models.json": ${JSON.stringify(JSON.stringify(models))},`, `"publish_model_cache.py": ${JSON.stringify(metadataScript)},`, '}', '');
const formatted = spawnSync('gofmt', [], {input: lines.join('\n'), encoding: 'utf8'});
if (formatted.status !== 0) throw new Error(formatted.stderr);
const target = path.join(root, 'apps/native/internal/infrastructure/managed/resources_generated.go');
if (process.argv.includes('--check')) {
 if (await readFile(target, 'utf8') !== formatted.stdout) throw new Error('Native runtime resource drift: run pnpm native:runtime:generate');
} else { await mkdir(path.dirname(target), {recursive:true}); await writeFile(target, formatted.stdout); }
console.log('Native runtime resources match shared runtime sources, Python scripts and platform locks.');
