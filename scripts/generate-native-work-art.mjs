import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "packages/desktop-resources/images");
const output = path.join(root, "apps/native/internal/desktop/presentation/work-art");
const check = process.argv.includes("--check");
const files = [
  ["work-maps/niuma-market.webp", "niuma-market.webp"],
  ["work-maps/farm-isometric.webp", "farm-isometric.webp"],
  ["work-maps/mine-map.webp", "mine-map.webp"],
  ["work-maps/factory-map.webp", "factory-map.webp"],
  ["work-maps/convenience-store-map.webp", "convenience-store-map.webp"],
  ["farm-layers/farm-background.png", "farm-background.png"],
  ["farm-layers/plot-wheat-soil.png", "plot-wheat-soil.png"],
  ["farm-layers/plot-carrot-soil.png", "plot-carrot-soil.png"],
  ["farm-layers/plot-tomato-soil.png", "plot-tomato-soil.png"],
  ...["wheat", "carrot", "tomato", "pumpkin", "corn", "strawberry", "blueberry", "potato"].map((key) => [`farm-layers/crop-${key}-overlay.png`, `crop-${key}-overlay.png`]),
  ...Array.from({ length: 8 }, (_, i) => [`farm-layers/dog-patrol/dog-walk-${String(i + 1).padStart(2, "0")}.png`, `dog-walk-${String(i + 1).padStart(2, "0")}.png`]),
  ["work-maps/content/mine-worker-shallow-content.png", "mine-worker-shallow.png"],
  ["work-maps/content/mine-worker-deep-content.png", "mine-worker-deep.png"],
  ["work-maps/content/mine-worker-glowing-content.png", "mine-worker-glowing.png"],
  ...["factory-basic-assembly", "factory-rush-order", "factory-precision-check", "store-day-shift", "store-evening-shift", "store-night-shift"].map((key) => [`work-maps/content/${key}-content.png`, `${key}.png`]),
  ...["mine", "factory", "store"].flatMap((kind) => Array.from({ length: 9 }, (_, i) => [`work-maps/content/${kind}-worker-standard-frame-${i + 1}.png`, `${kind}-worker-frame-${i + 1}.png`])),
];

const lines = [
  "// Code generated by scripts/generate-native-work-art.mjs; DO NOT EDIT.",
  "// Original Liberty farm and work-game art embedded for the Go desktop.",
  "package presentation",
  "",
  "import (",
  '\t"embed"',
  '\t"sync"',
  "",
  '\t"github.com/egoist/mygo/ui"',
  ")",
  "",
  "//go:embed work-art/*",
  "var workArtFiles embed.FS",
  "",
  "var workArtCache sync.Map",
  "",
  "func WorkArt(name string) ui.ImageSource {",
  "\tif cached, ok := workArtCache.Load(name); ok { return cached.(ui.ImageSource) }",
  "\tdata, err := workArtFiles.ReadFile(\"work-art/\" + name)",
  "\tif err != nil { panic(err) }",
  "\timage, err := ui.DecodeImage(data)",
  "\tif err != nil { panic(err) }",
  "\tvalue, _ := workArtCache.LoadOrStore(name, image)",
  "\treturn value.(ui.ImageSource)",
  "}",
  "",
];
const formatted = spawnSync("gofmt", [], { input: lines.join("\n"), encoding: "utf8" });
if (formatted.status !== 0) throw new Error(formatted.stderr || "gofmt failed");
const generated = path.join(root, "apps/native/internal/desktop/presentation/work_art_generated.go");
if (!check) await mkdir(output, { recursive: true });
const expected = new Set(files.map(([, name]) => name));
if (expected.size !== files.length) throw new Error("Duplicate native work art output name");
const unexpected = (await readdir(output)).filter((name) => !expected.has(name));
if (unexpected.length) throw new Error(`Unexpected native work art: ${unexpected.join(", ")}`);
for (const [original, name] of files) {
  const from = path.join(source, original);
  const to = path.join(output, name);
  if (check) {
    const [a, b] = await Promise.all([readFile(from), readFile(to)]);
    if (!a.equals(b)) throw new Error(`Native work art drift: ${name}; run pnpm native:work-art:generate`);
  } else await copyFile(from, to);
}
if (check) {
  if (!(await readFile(generated)).equals(Buffer.from(formatted.stdout))) throw new Error("Native work art index drift; run pnpm native:work-art:generate");
} else await writeFile(generated, formatted.stdout);
console.log(`Embedded ${files.length} original farm and work-game assets.`);
