// Read only the shared public verification key.
// Never read or copy the legacy short-code signing secret into native resources.
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const encoded = (await readFile(path.join(root, 'packages/desktop-resources/redemption/public-key.b64'), 'utf8')).trim();
const bytes = Buffer.from(encoded, 'base64');
if (bytes.length !== 32 || bytes.toString('base64') !== encoded) throw new Error('Invalid redemption public verification key');
const text = [
  '// Code generated by scripts/generate-native-redemption.mjs; DO NOT EDIT.',
  '// Public Ed25519 verification key shared with the original Rust client.',
  'package domain', '',
  `var petRedemptionPublicKey = [32]byte{${[...bytes].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(',')},}`, ''
].join('\n');
const formatted = spawnSync('gofmt', [], { input: text, encoding: 'utf8' });
if (formatted.status !== 0) throw new Error('Failed to format redemption public key');
const output = path.join(root, 'apps/native/internal/domain/pet_redemption_key_generated.go');
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== formatted.stdout) throw new Error('Native redemption public key drifted; run pnpm native:redemption:generate');
} else await writeFile(output, formatted.stdout);
console.log('Native redemption verification key matches the shared public key.');
