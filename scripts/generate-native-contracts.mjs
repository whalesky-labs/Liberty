import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "packages/shared-types/schemas");
const target = path.join(root, "apps/native/internal/contracts/schemas_generated.go");
async function schemas(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (await Promise.all(entries.map((entry) => entry.isDirectory()
    ? schemas(path.join(directory, entry.name))
    : [path.join(directory, entry.name)]))).flat().filter((p) => p.endsWith(".schema.json"));
}
const lines = ["// Code generated by scripts/generate-native-contracts.mjs; DO NOT EDIT.", "// Source: packages/shared-types/schemas. No network schema loading.", "package contracts", "", "var schemas = map[string]string{"];
for (const file of (await schemas(source)).sort()) {
  const schema = JSON.parse(await readFile(file, "utf8"));
  if (!schema.$id) throw new Error(`Missing schema id: ${file}`);
  lines.push(`\t${JSON.stringify(schema.$id)}: ${JSON.stringify(JSON.stringify(schema))},`);
}
lines.push("}", "");
const formatted = spawnSync("gofmt", [], { input: lines.join("\n"), encoding: "utf8" });
if (formatted.status !== 0) throw new Error(formatted.stderr || "gofmt failed");
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== formatted.stdout) throw new Error("Native schema drift; run pnpm native:contracts:generate");
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, formatted.stdout);
}
console.log("Native embedded schemas match shared contracts.");
