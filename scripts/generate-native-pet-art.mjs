import { mkdir, readdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const original=path.join(root,'packages/desktop-resources/images/pet');
const output=path.join(root,'apps/native/internal/desktop/presentation/pet-art');
const check=process.argv.includes('--check');
async function files(directory){
 const entries=await readdir(directory,{withFileTypes:true});
 return (await Promise.all(entries.filter(e=>!e.name.startsWith('.')).map(e=>e.isDirectory()?files(path.join(directory,e.name)):[path.join(directory,e.name)]))).flat();
}
const copies=[];
const shops=new Set();
for(const from of await files(path.join(original,'shop'))){
 if(!from.endsWith('.png')) continue;
 const name=path.basename(from);
 if(shops.has(name)) throw new Error('Duplicate original shop art name');
 shops.add(name);copies.push([from,`shop-${name}`]);
}
const groups=['crush','defecate','drive','eat','gaming','pants','reading','rope','run','slack','sleep','snow','studying','toy','work'];
const frames={};
for(const group of groups){
 const candidates=new Map();
 for(const directory of [path.join(original,group),path.join(original,'action',group)]){
  let list=[];try{list=await files(directory);}catch(error){if(error.code!=='ENOENT')throw error;}
  for(const file of list){
   const m=path.basename(file).match(/^(?:[a-z]+_)?(\d+)\.png$/);
   if(m && +m[1]>0) candidates.set(+m[1],file);
  }
 }
 frames[group]=[...candidates.entries()].sort((a,b)=>a[0]-b[0]).map(([i,from])=>{
  const name=`action-${group}-${i}.png`;copies.push([from,name]);return name;
 });
 if(!frames[group].length)throw new Error(`No original pet frames: ${group}`);
}
const source=`// Code generated by scripts/generate-native-pet-art.mjs; DO NOT EDIT.
// Original shop artwork and action frames; action/ takes precedence as in React.
package presentation

import("embed";"time";"github.com/egoist/mygo/ui")
//go:embed pet-art/*
var petArtFiles embed.FS
var petArtCache = newBitmapCache(8*1024*1024)
var petFrames=map[string][]string{
${Object.entries(frames).map(([k,v])=>`${JSON.stringify(k)}: {${v.map(s=>JSON.stringify(s)).join(',')}},`).join('\n')}
}
func PetArt(asset string) ui.ImageSource { return petBitmap("shop-"+asset+".png") }
// PetActionReference is a still frame for the isolated model-review tool.
func PetActionReference(group string) ui.ImageSource {
 frames:=petFrames[group];if len(frames)==0 {frames=petFrames["slack"]}
 return petBitmap(frames[len(frames)/2])
}
// PetActionPose follows the explicit pose clock of the native 3D review.
func PetActionPose(group string,index int) ui.ImageSource {
 frames:=petFrames[group];if len(frames)==0 {frames=petFrames["slack"]}
 return petBitmap(frames[max(0,min(index,len(frames)-1))])
}
func PetFrame(c *ui.Context,group string) ui.ImageSource {
 frames:=petFrames[group];if len(frames)==0 {frames=petFrames["slack"]}
 interval:=300*time.Millisecond
 index:=int((c.Now().UnixNano()/int64(interval))%int64(len(frames)));if index<0{index=0}
 c.After(interval)
 return petBitmap(frames[index])
}
func petBitmap(name string) ui.ImageSource {
 if file,err:=petArtFiles.Open("pet-art/"+name);err!=nil {name="shop-gift_box.png"}else{file.Close()}
 return petArtCache.load(petArtFiles,"pet-art/"+name,320)
}
`;
const formatted=spawnSync('gofmt',[],{input:source,encoding:'utf8'});
if(formatted.status!==0)throw new Error(formatted.stderr);
if(!check)await mkdir(output,{recursive:true});
for(const [from,name] of copies){
 const to=path.join(output,name);
 if(check){if(!(await readFile(from)).equals(await readFile(to)))throw new Error(`Pet art drift: ${name}`);}
 else await copyFile(from,to);
}
const generated=path.join(path.dirname(output),'pet_art_generated.go');
if(check){if(await readFile(generated,'utf8')!==formatted.stdout)throw new Error('Native pet art index drift');}
else await writeFile(generated,formatted.stdout);
console.log(`Native pet art matches ${shops.size} original shop images and ${copies.length-shops.size} action frames.`);
