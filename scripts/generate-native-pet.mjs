import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCatalog, parseStages } from '../packages/desktop-resources/pet/validate.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const resources = path.join(root, 'packages/desktop-resources/pet');
const decoder = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true });
const stages = parseStages(decoder.decode(await readFile(path.join(resources, 'stages.json'))));
const items = parseCatalog(decoder.decode(await readFile(path.join(resources, 'catalog.json'))), stages);

const lines = [
  '// Code generated by scripts/generate-native-pet.mjs; DO NOT EDIT.',
  '// Original Rust catalog seed mappings and stage thresholds.',
  'package domain',
  '',
  `const petCatalogJSON = ${JSON.stringify(JSON.stringify(items))}`,
  `const petStagesJSON = ${JSON.stringify(JSON.stringify(stages))}`,
  '',
];
const formatted = spawnSync('gofmt', [], { input: lines.join('\n'), encoding: 'utf8' });
if (formatted.error) throw formatted.error;
if (formatted.status !== 0) throw new Error(formatted.stderr);
const target = path.join(root, 'apps/native/internal/domain/pet_generated.go');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== formatted.stdout) {
    throw new Error('Native pet data drifted; run pnpm native:pet:generate');
  }
} else {
  await writeFile(target, formatted.stdout);
}
console.log(`Native pet data matches ${items.length} catalog items and ${stages.length} stages.`);
