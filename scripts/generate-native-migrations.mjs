import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const resources = path.join(root, 'packages/desktop-resources/database');
const destination = path.join(root, 'apps/native/internal/infrastructure/repositories/schema/migrations_generated.go');
const version = 10;
const columnAddition = /^ALTER TABLE [a-z_][a-z0-9_]* ADD COLUMN [a-z_][a-z0-9_]* /;
const plans = [
  ['baselineSQL', 'v01-baseline.sql', ['PRAGMA ']],
  ['settingsUpgradeSQL', 'v02-settings.sql', [...Array(15).fill(columnAddition), 'UPDATE ']],
  ['runtimeSourcesSQL', 'v02-runtime-sources.sql', ['UPDATE ', 'INSERT ']],
  ['settingsRevisionSQL', 'v04-settings-revisions.sql', [columnAddition]],
  ['jobRunsSQL', 'v05-job-runs.sql', ['CREATE ', 'INSERT ']],
  ['workTablesSQL', 'v06-work-tables.sql', ['CREATE ']],
  ['summaryRunsSQL', 'v07-summary-runs.sql', [
    'CREATE ', ...Array(9).fill(columnAddition), 'CREATE ', 'UPDATE ', 'UPDATE ', 'UPDATE ', 'CREATE UNIQUE INDEX ', 'UPDATE ',
  ]],
  ['jobDeletionSQL', 'v08-job-deletions.sql', ['CREATE ']],
  ['runnerProtocolSQL', 'v09-runner-protocol.sql', ['ALTER ']],
  ['credentialCleanupSQL', 'v10-credential-cleanup-intents.sql', ['CREATE ']],
];

const lines = [
  '// Code generated by scripts/generate-native-migrations.mjs; DO NOT EDIT.',
  '// SQL and built-in templates come from packages/desktop-resources/database.',
  'package schema', '', `const CurrentVersion = ${version}`, '',
];
for (const [name, filename, expected] of plans) {
  const text = await readFile(path.join(resources, filename), 'utf8');
  const blocks = text.replaceAll('\r\n', '\n').split('-- next block').map(block => block.trim());
  if (blocks.length !== expected.length || blocks.some((block, index) => {
    const kind = expected[index];
    return typeof kind === 'string' ? !block.startsWith(kind) : !kind.test(block);
  })) throw new Error(`Unexpected SQL block count or kind in ${filename}`);
  lines.push(`var ${name} = []string{`, ...blocks.map(block => `${JSON.stringify(block)},`), '}', '');
}

const templateFields = {
  id: 'string', name: 'string', description: 'string', prompt: 'string',
  includeSpeakerByDefault: 'boolean', includeTimestampByDefault: 'boolean', builtin: 'boolean',
  createdAt: 'string', updatedAt: 'string',
};
const fields = Object.entries(templateFields);
const templates = JSON.parse(await readFile(path.join(resources, 'builtin-summary-templates.json'), 'utf8'));
if (!Array.isArray(templates) || templates.length !== 5 || templates.some(template => (
  template === null || typeof template !== 'object' || Object.keys(template).length !== fields.length ||
  fields.some(([key, type]) => typeof template[key] !== type || (type === 'string' && !template[key].trim())) ||
  !template.id.startsWith('builtin-') || template.builtin !== true
)) || new Set(templates.map(template => template.id)).size !== templates.length) {
  throw new Error('Invalid built-in summary templates');
}
const orderedTemplates = templates.map(template => Object.fromEntries(fields.map(([key]) => [key, template[key]])));
lines.push(`const builtinTemplatesJSON = ${JSON.stringify(JSON.stringify(orderedTemplates))}`, '');

const formatted = spawnSync('gofmt', [], { input: lines.join('\n'), encoding: 'utf8' });
if (formatted.status !== 0) throw formatted.error ?? new Error(formatted.stderr);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== formatted.stdout) {
    throw new Error('Native migration resources drifted; run pnpm native:migrations:generate');
  }
} else {
  await writeFile(destination, formatted.stdout);
}
console.log('Native migrations and built-in templates match the shared database resources.');
