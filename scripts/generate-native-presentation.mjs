import { readFile, mkdir, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
import ts from "typescript";
import { icons } from "@iconify-json/f7";
import { getIconData, iconToSVG } from "@iconify/utils";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const resources = "packages/desktop-resources";
const output = path.join(root, "apps/native/internal/desktop/presentation");
const check = process.argv.includes("--check");

// These source objects deliberately contain only literals. Refuse expressions
// instead of evaluating TypeScript while generating the native resources.
function literal(node) {
  if (ts.isAsExpression(node) || ts.isSatisfiesExpression(node)) return literal(node.expression);
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text;
  if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map((p) => {
    if (!ts.isPropertyAssignment(p) || !p.name || ts.isComputedPropertyName(p.name)) throw new Error("Expected literal property");
    return [p.name.text, literal(p.initializer)];
  }));
  throw new Error("Expected a literal presentation object");
}

async function readConstant(relative, name) {
  const source = ts.createSourceFile(relative, await readFile(path.join(root, relative), "utf8"), ts.ScriptTarget.Latest, true);
  let result;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(source) === name) result = literal(node.initializer);
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (!result) throw new Error(`Missing presentation constant: ${name}`);
  return result;
}

function flatten(value, prefix = "") {
  return Object.entries(value).flatMap(([key, entry]) => {
    const name = prefix ? `${prefix}.${key}` : key;
    return typeof entry === "string" ? [[name, entry]] : flatten(entry, name);
  });
}

const messages = await Promise.all(["zh-CN", "en-US"].map(async (locale) => [locale, flatten(await readConstant(
  `${resources}/i18n/messages/${locale}.ts`, locale === "zh-CN" ? "zhCNMessages" : "enUSMessages",
))]));
const petSources = await readConstant(`${resources}/i18n/petSourceLabels.ts`, "petSourceLabels");
for (const [locale, entries] of messages) {
  for (const [key, label] of Object.entries(petSources)) {
    const text = label[locale === "en-US" ? "en" : "zh"];
    if (!text) throw new Error(`Missing pet source translation: ${key}`);
    entries.push([`petSource.${key}`, text]);
  }
}
if (messages[0][1].map(([key]) => key).sort().join("\n") !== messages[1][1].map(([key]) => key).sort().join("\n")) {
  throw new Error("Native presentation requires identical bilingual message keys");
}
const iconSource = `${resources}/presentation/icons.ts`;
const iconNames = await readConstant(iconSource, "navIconNames");
const shellIconPaths = await readConstant(iconSource, "shellIconPaths");
const lines = ["// Code generated by scripts/generate-native-presentation.mjs; DO NOT EDIT.",
  "// Source: shared desktop messages and icons.", "package presentation", "", "var messages = map[string]map[string]string{"];
for (const [locale, entries] of messages) {
  lines.push(`${JSON.stringify(locale)}: {`);
  for (const [key, value] of entries) lines.push(`${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  lines.push("},");
}
lines.push("}", "", "var iconSources = map[string]string{");
for (const [key, name] of Object.entries(iconNames)) {
  const data = getIconData(icons, name);
  if (!data) throw new Error(`Missing original icon: ${name}`);
  const svg = iconToSVG(data, { height: "16", width: "16" });
  lines.push(`${JSON.stringify(key)}: ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${svg.attributes.viewBox}" width="16" height="16">${svg.body}</svg>`)},`);
}
for (const [key, data] of Object.entries(shellIconPaths)) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="currentColor" d="${data}"/></svg>`;
  lines.push(`${JSON.stringify(key)}: ${JSON.stringify(svg)},`);
}
lines.push("}", "", `const Version = ${JSON.stringify(JSON.parse(await readFile(path.join(root,"package.json"),"utf8")).version)}`, "");
const formatted = spawnSync("gofmt", [], { input: lines.join("\n"), encoding: "utf8" });
if (formatted.status !== 0) throw new Error(formatted.stderr || "gofmt failed");
const artifacts = [
  ["resources_generated.go", Buffer.from(formatted.stdout)],
  ["sidebar-mascot.webp", await readFile(path.join(root, resources, "presentation/sidebar-mascot.webp"))],
];
if (!check) await mkdir(output, { recursive: true });
for (const [name, bytes] of artifacts) {
  const target = path.join(output, name);
  if (check) {
    if (!(await readFile(target)).equals(bytes)) throw new Error(`Native presentation drift: ${name}; run pnpm native:presentation:generate`);
  } else await writeFile(target, bytes);
}
console.log("Native messages, icons and mascot match the shared desktop sources.");
await import("./generate-native-bloub.mjs");
